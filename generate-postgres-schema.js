// Gera um schema PostgreSQL a partir do schema-export.json.
// Somente gera arquivo local; não conecta nem altera o Supabase.
const fs = require('fs');
const path = require('path');

const input = process.env.SCHEMA_INPUT || path.join(__dirname, 'schema-export.json');
const output = process.env.SCHEMA_SQL_OUTPUT || path.join(__dirname, 'postgres-schema.sql');
const schema = JSON.parse(fs.readFileSync(input, 'utf8'));

function quoteIdentifier(value) {
  return `"${String(value).replace(/"/g, '""')}"`;
}

function tableKey(tableSchema, tableName) {
  return `${tableSchema}.${tableName}`;
}

function postgresType(column) {
  const type = String(column.data_type).toLowerCase();
  if (type === 'nvarchar' || type === 'varchar' || type === 'nchar' || type === 'char') {
    return !column.max_length || column.max_length < 0 ? 'text' : `varchar(${column.max_length})`;
  }
  if (type === 'uniqueidentifier') return 'text';
  if (type === 'datetime' || type === 'datetime2' || type === 'smalldatetime') return 'timestamptz';
  if (type === 'int' || type === 'smallint' || type === 'tinyint') return 'integer';
  if (type === 'bigint') return 'bigint';
  if (type === 'bit') return 'integer';
  if (type === 'decimal' || type === 'numeric' || type === 'money' || type === 'smallmoney') return 'numeric';
  if (type === 'float') return 'double precision';
  if (type === 'real') return 'real';
  if (type === 'date') return 'date';
  if (type === 'time') return 'time';
  if (type === 'binary' || type === 'varbinary' || type === 'image') return 'bytea';
  return 'text';
}

function postgresDefault(value) {
  if (!value) return null;
  let result = String(value).trim();
  while (result.startsWith('(') && result.endsWith(')')) result = result.slice(1, -1).trim();
  result = result.replace(/^N('.*')$/i, '$1');
  result = result.replace(/^getdate\(\)$/i, 'CURRENT_TIMESTAMP');
  result = result.replace(/^newid\(\)$/i, 'gen_random_uuid()');
  return result;
}

function groupedConstraints(type) {
  const groups = new Map();
  for (const key of schema.keys || []) {
    if (key.constraint_type !== type) continue;
    const groupKey = `${key.table_schema}.${key.table_name}.${key.constraint_name}`;
    if (!groups.has(groupKey)) {
      groups.set(groupKey, { ...key, columns: [] });
    }
    groups.get(groupKey).columns.push(key);
  }
  for (const group of groups.values()) {
    group.columns.sort((a, b) => Number(a.key_ordinal || 0) - Number(b.key_ordinal || 0));
  }
  return [...groups.values()];
}

const lines = [
  '-- Gerado a partir do schema-export.json; revisar antes de executar no Supabase.',
  '-- IDs foram mantidos como text para preservar compatibilidade com o SQL Server legado.',
  'CREATE EXTENSION IF NOT EXISTS pgcrypto;',
  '',
];

for (const table of schema.tables) {
  const columns = schema.columns.filter(column => (
    column.table_schema === table.table_schema && column.table_name === table.table_name
  ));
  lines.push(`CREATE TABLE IF NOT EXISTS ${quoteIdentifier(table.table_name)} (`);
  lines.push(columns.map((column, index) => {
    const nullable = column.is_nullable === 'NO' ? ' NOT NULL' : '';
    const identity = Number(column.is_identity) === 1 ? ' GENERATED BY DEFAULT AS IDENTITY' : '';
    const defaultValue = postgresDefault(column.column_default);
    const defaultSql = defaultValue ? ` DEFAULT ${defaultValue}` : '';
    const suffix = index === columns.length - 1 ? '' : ',';
    return `  ${quoteIdentifier(column.column_name)} ${postgresType(column)}${identity}${nullable}${defaultSql}${suffix}`;
  }).join('\n'));
  lines.push(');', '');
}

lines.push(
  '-- Colunas exigidas pelas rotas atuais do backend Node.',
  'ALTER TABLE "settings" ADD COLUMN IF NOT EXISTS "empresa_id" text;',
  'ALTER TABLE "checkpoints" ADD COLUMN IF NOT EXISTS "location" varchar(100);',
  'ALTER TABLE "empresas" ADD COLUMN IF NOT EXISTS "latitude" double precision;',
  'ALTER TABLE "empresas" ADD COLUMN IF NOT EXISTS "longitude" double precision;',
  ''
);

for (const type of ['PRIMARY KEY', 'UNIQUE']) {
  for (const constraint of groupedConstraints(type)) {
    const table = quoteIdentifier(constraint.table_name);
    const name = quoteIdentifier(constraint.constraint_name);
    const columns = constraint.columns.map(column => quoteIdentifier(column.column_name)).join(', ');
    lines.push(`DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = '${String(constraint.constraint_name).replace(/'/g, "''")}') THEN`);
    lines.push(`  ALTER TABLE ${table} ADD CONSTRAINT ${name} ${type === 'PRIMARY KEY' ? 'PRIMARY KEY' : 'UNIQUE'} (${columns});`);
    lines.push('END IF; END $$;', '');
  }
}

for (const constraint of groupedConstraints('FOREIGN KEY')) {
  if (!constraint.referenced_table || !constraint.referenced_column) continue;
  const table = quoteIdentifier(constraint.table_name);
  const name = quoteIdentifier(constraint.constraint_name);
  const columns = constraint.columns.map(column => quoteIdentifier(column.column_name)).join(', ');
  const referenced = quoteIdentifier(constraint.referenced_table);
  const referencedColumns = constraint.columns.map(column => quoteIdentifier(column.referenced_column)).join(', ');
  lines.push(`DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = '${String(constraint.constraint_name).replace(/'/g, "''")}') THEN`);
  lines.push(`  ALTER TABLE ${table} ADD CONSTRAINT ${name} FOREIGN KEY (${columns}) REFERENCES ${referenced} (${referencedColumns});`);
  lines.push('END IF; END $$;', '');
}

fs.writeFileSync(output, `${lines.join('\n')}\n`);
console.log(`✅ Schema PostgreSQL gerado em: ${output}`);
