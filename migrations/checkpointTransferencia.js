// migrations/checkpointTransferencia.js - checkpoint cadastrado pelo super admin e transferido para o buffet
//
// Só ACRESCENTA colunas e relaxa uma restrição; a chave atual (checkpointId) e tudo que depende dela continuam
// como estão, então as rotas dos ESP32 e do buffet seguem funcionando. A troca da chave para o `id` vem depois.
//
//   id                   autoincremento, único (vira a chave primária na etapa da troca)
//   numCheck             o número do checkpoint (o antigo checkpointId digitado); único por buffet
//   macAddress           MAC do ESP32 (AA:BB:CC:DD:EE:FF), único no sistema; os antigos o aprendem depois
//   statusTransferencia  estoque | pendente | aceito (ver utils/checkpointTransferencia.js)
//   empresaDestinoId     buffet para o qual foi transferido, enquanto pendente
//   transferidoEm        quando foi transferido
//
// Em estoque e pendente o checkpoint não tem buffet nem evento (empresaId e eventoId NULL), por isso as telas
// atuais, que filtram por eventoId e empresaId, não o enxergam.
const { query, DB_DRIVER } = require('../database');

async function ensureCheckpointTransferSchema(db = { query }) {
  const isPostgres = DB_DRIVER === 'postgres' || DB_DRIVER === 'postgresql';
  if (!isPostgres) return;

  await db.query('ALTER TABLE pontoVerificacao ADD COLUMN IF NOT EXISTS id integer GENERATED BY DEFAULT AS IDENTITY');
  await db.query('CREATE UNIQUE INDEX IF NOT EXISTS uq_pontoverificacao_id ON pontoVerificacao (id)');

  await db.query('ALTER TABLE pontoVerificacao ADD COLUMN IF NOT EXISTS numCheck varchar(40)');
  await db.query('ALTER TABLE pontoVerificacao ADD COLUMN IF NOT EXISTS macAddress varchar(17)');
  await db.query("ALTER TABLE pontoVerificacao ADD COLUMN IF NOT EXISTS statusTransferencia varchar(10) NOT NULL DEFAULT 'aceito'");
  await db.query('ALTER TABLE pontoVerificacao ADD COLUMN IF NOT EXISTS empresaDestinoId varchar(36)');
  await db.query('ALTER TABLE pontoVerificacao ADD COLUMN IF NOT EXISTS transferidoEm timestamptz');

  // Em estoque o checkpoint ainda não tem evento.
  await db.query('ALTER TABLE pontoVerificacao ALTER COLUMN eventoId DROP NOT NULL');

  // O número dos checkpoints que já existem é o ID que o recreacionista digitou (a coluna `codigo`).
  await db.query('UPDATE pontoVerificacao SET numCheck = codigo WHERE numCheck IS NULL AND codigo IS NOT NULL');

  await db.query('CREATE UNIQUE INDEX IF NOT EXISTS uq_pontoverificacao_mac ON pontoVerificacao (macAddress) WHERE macAddress IS NOT NULL');
  try {
    await db.query('CREATE UNIQUE INDEX IF NOT EXISTS uq_pontoverificacao_empresa_numcheck ON pontoVerificacao (empresaId, LOWER(numCheck)) WHERE numCheck IS NOT NULL');
  } catch (erro) {
    // Dados antigos com número repetido no mesmo buffet: avisa e segue; as rotas novas checam antes de gravar.
    console.warn(`⚠️ Índice de número único por buffet não criado: ${erro.message}`);
  }
}

module.exports = { ensureCheckpointTransferSchema };
